#!/bin/bash
# DATA-6 section 8: import the eight delivered cells as OA schematics and symbols with Cadence's own
# netlist->schematic importer (spiceIn / Analog Schematic Generation).
#
# Copy-by-value of the accepted scripts/sc1_s3c_asg.sh route (which is NOT modified): SCH-1/SCH-3 and
# S3-C measured that this build's batch session has no Schematic Editor package -- schCreate,
# schCreateWire, schCreateSym, symCreate and dbCreateFig are undefined -- while spiceIn reads
# connectivity out of the netlist itself. For DATA-6 that is exactly what is wanted: the eight cells
# are imported from the same masters the native TT round simulated, not drawn from memory.
#
# The import copy is generated by scripts/dd1_d6_golden.py, whose own selftest resolves the emitted
# copy back into devices and requires the identical 29-MOS circuit. The guards below re-check that
# claim on the bytes about to be handed to the tool, and refuse to overwrite anything.
#
#   bash scripts/dd1_d6_asg.sh
set -u

PROJ="${PROJ:-/root/microled_ai_project}"
D6="$PROJ/cadence_work/data_d6_oa"
LIB="${LIB:-microled_data_d6}"
TOP="${TOP:-dd1_d6_asg_shell}"
NL="${NL:-$D6/asg_in/dd1_d6_import.scs}"
CELLS="${CELLS:-c2mos_dff sc1_scan_gate dd1_inv18 dd1_control_1ch data_sink_1ch data_bias_ref dd1_sink_unit_1ch dd1_data_top_1ch}"
EXPECT_MOS="${EXPECT_MOS:-29}"

[ -f "$D6/cds.lib" ] || { echo "REFUSE: no isolated cds.lib in $D6 -- run scripts/dd1_d6_setup_oa.sh"; exit 9; }
[ -r "$NL" ] || { echo "REFUSE: import copy unreadable: $NL"; exit 9; }

fail=0
for C in $CELLS; do
  grep -qE "^subckt[[:space:]]+${C}([[:space:]]|\()" "$NL" \
    || { echo "REFUSE: import copy has no 'subckt $C' header"; fail=1; }
  grep -qE "^ends[[:space:]]+${C}([[:space:]]|\$)" "$NL" \
    || { echo "REFUSE: subckt $C has no matching ends"; fail=1; }
done
grep -qE "^subckt[[:space:]]+${TOP}([[:space:]]|\()" "$NL" && {
  echo "REFUSE: shell $TOP is also a subckt in the file (SPICEIN-77)"; fail=1; } || true
MOS=$(grep -cE '^[[:space:]]+(M|mp|mn)[A-Za-z_0-9]*[[:space:]]*\(' "$NL")
[ "$MOS" = "$EXPECT_MOS" ] \
  || { echo "REFUSE: import copy holds $MOS MOS lines, this task's top expands to $EXPECT_MOS"; fail=1; }
grep -qiE '(^|[[:space:]])(iprobe|vsource|isource|capacitor)([[:space:]]|$)' "$NL" && {
  echo "REFUSE: the import copy still carries bench wiring (a source, probe or capacitor)"; fail=1; } || true
XU=$(grep -E '^[[:space:]]+Xunit[[:space:]]*\(' "$NL" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]][[:space:]]*/ /g' -e 's/[[:space:]]*$//')
[ "$XU" = "Xunit (d clk blank iref_in vcas data_out vdd18 vss) dd1_sink_unit_1ch" ] \
  || { echo "REFUSE: the formal top does not bind the unit as the task book states -- got [$XU]"; fail=1; }
XM=$(grep -E '^[[:space:]]+Xmask[[:space:]]*\(' "$NL" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]][[:space:]]*/ /g' -e 's/[[:space:]]*$//')
[ "$XM" = "Xmask (qbar blank data_en vdd vss) sc1_scan_gate" ] \
  || { echo "REFUSE: the mask gate instance is not the accepted wiring -- got [$XM]"; fail=1; }
for C in $TOP $CELLS; do
  [ -e "$D6/$LIB/$C" ] && { echo "REFUSE: $LIB/$C already exists -- nothing is overwritten"; fail=1; }
done
[ "$fail" = "0" ] || { echo "D6_ASG: REFUSED"; exit 9; }

LOGD="$D6/logs"
STAMP=$(date +%Y%m%d_%H%M%S)
ASLOG="$LOGD/asg_spiceIn_$STAMP.log"
PARAM="$D6/asg_in/dd1_d6_param.il"
cat > "$PARAM" <<EOF
;; generated by scripts/dd1_d6_asg.sh -- plumbing only: names, paths, libraries, mode flags.
;; No W/L, no model and no connectivity value is set here; those come only from the import copy.
spiceInParams = list(nil
    'topCell         "$TOP"
    'language        "SPECTRE"
    'netlistFile     "$NL"
    'outputLib       "$LIB"
    'refLibList      "smic18mmrf analogLib"
    'outputViewType  "schematic"
    'outputViewName  "schematic"
    'simName         "spectre"
    'outputSimName   "spectre"
    'overwriteCells  "NONE"
    'logFile         "$ASLOG"
)
EOF
echo "IMPORT_COPY=$NL  TOP=$TOP  CELLS=$(echo "$CELLS" | wc -w)  MOS_LINES=$MOS"
echo "PARAM_FILE=$PARAM"

# shellcheck disable=SC1091
. "$PROJ/skill/cad_env.sh" || { echo "FATAL: cadence env load failed"; exit 8; }
cd "$D6" || exit 9
[ -n "$(command -v spiceIn)" ] || { echo "FATAL: spiceIn not on the Cadence PATH"; exit 8; }

timeout "${TMO:-420}" spiceIn -param "$PARAM"
rc=$?
echo "ASG rc=$rc"
[ -f "$D6/spiceIn.log" ] && cp -f "$D6/spiceIn.log" "$LOGD/asg_cwdlog_$STAMP.log"
echo "ASG_LOG=$ASLOG"
echo "--- log tail ---"
tail -20 "$ASLOG" 2>&1
echo "--- error scan ---"
grep -icE 'error|\*\*E|not found|cannot|unable|refuse' "$ASLOG" 2>/dev/null | sed 's/^/ASG_PROBLEM_LINES: /'
echo "--- delivered views ---"
for C in $CELLS; do
  SCH=no; SYM=no
  [ -d "$D6/$LIB/$C/schematic" ] && SCH=yes
  ls -d "$D6/$LIB/$C"/symbol* >/dev/null 2>&1 && SYM=yes
  echo "CELL=$C schematic=$SCH symbol=$SYM"
done
[ "$rc" = "0" ] || { echo "D6_ASG: FAIL"; exit 1; }
echo "D6_ASG: DONE lib=$LIB cells=$(echo "$CELLS" | wc -w) mos=$MOS"
exit 0
