#!/bin/bash
# SCAN-1 S3-C section 3: import the derived eight-cell hierarchy as OA schematics and symbols
# with Cadence's own netlist->schematic importer (spiceIn / Analog Schematic Generation).
#
# Why this tool and not SKILL drawing: scripts/sc1_s3c_oa_probe.il measured, in this build's batch
# session, that dbCreateFig, ddCreateCell and the whole Schematic Editor package (schCreate,
# schCreateWire, schCheck, schCreateSym, symCreate, schConvSch2Sym) are undefined, while dbAccess's
# object API is present. spiceIn is the route SCH-1 and SCH-3 proved: it reads connectivity out of
# the netlist file rather than out of anyone's head, which is exactly what S3-C requires.
#
# The import copy comes from scripts/sc1_s3c_golden.py, so the eight cells and the sizes are
# derived from the six frozen masters. The guards below re-check that claim on the bytes that are
# about to be handed to the tool, and refuse to overwrite anything.
set -u

PROJ="${PROJ:-/root/microled_ai_project}"
S3C="$PROJ/cadence_work/s3c_oa"
LIB="${LIB:-microled_scan_s3c}"
TOP="${TOP:-s3c_asg_shell}"
NL="${NL:-$S3C/asg_in/sc1_s3c_import.scs}"
CELLS="${CELLS:-c2mos_dff sc1_scan_gate sc1_ls_core_r2d sc1_ls_c1_r2d sc1_ls_c1_top_r2d sc1_r3_scan_chain_1ch sc1_s3b_p33_bank_7 sc1_scan_power_1ch_s3c}"

[ -f "$S3C/cds.lib" ] || { echo "REFUSE: no isolated cds.lib in $S3C"; exit 9; }
[ -r "$NL" ] || { echo "REFUSE: import copy unreadable: $NL"; exit 9; }

fail=0
for C in $CELLS; do
  grep -qE "^subckt[[:space:]]+${C}([[:space:]]|\()" "$NL" \
    || { echo "REFUSE: import copy has no 'subckt $C' header"; fail=1; }
  grep -qE "^ends[[:space:]]+${C}([[:space:]]|\$)" "$NL" \
    || { echo "REFUSE: subckt $C has no matching ends"; fail=1; }
done
grep -qE "^subckt[[:space:]]+${TOP}([[:space:]]|\()" "$NL" && {
  echo "REFUSE: topCell $TOP is also a subckt in the file (SPICEIN-77)"; fail=1; } || true
MOS=$(grep -cE '^[[:space:]]+(mp|mn)[A-Za-z_0-9]*[[:space:]]*\(' "$NL")
[ "$MOS" = "39" ] || { echo "REFUSE: import copy holds $MOS MOS lines, the golden expands to 39"; fail=1; }
grep -qiE '(^|[[:space:]])iprobe([[:space:]]|$)' "$NL" && {
  echo "REFUSE: the import copy still carries a measurement iprobe"; fail=1; } || true
XB=$(grep -E '^[[:space:]]+Xbank[[:space:]]*\(' "$NL" \
     | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]][[:space:]]*/ /g' -e 's/[[:space:]]*$//')
[ "$XB" = "Xbank (scan gate33 vscan) sc1_s3b_p33_bank_7" ] || {
  echo "REFUSE: the formal top does not merge bgate into gate33 -- got [$XB]"; fail=1; }
for C in $TOP $CELLS; do
  [ -e "$S3C/$LIB/$C" ] && { echo "REFUSE: $LIB/$C already exists -- nothing is overwritten"; fail=1; }
done
[ -e "$S3C/$LIB" ] && echo "LIB_DIR_ABSENT=no" || echo "LIB_DIR_ABSENT=yes (spiceIn must create it)"
[ "$fail" = "0" ] || { echo "S3C_ASG: REFUSED"; exit 9; }

LOGD="$S3C/logs"
STAMP=$(date +%Y%m%d_%H%M%S)
ASLOG="$LOGD/asg_spiceIn_$STAMP.log"
PARAM="$S3C/asg_in/sc1_s3c_param.il"
cat > "$PARAM" <<EOF
;; generated by scripts/sc1_s3c_asg.sh -- plumbing only: names, paths, libraries, mode flags.
;; No W/L, no model and no connectivity value is set here; those come only from the import copy.
spiceInParams = list(nil
    'topCell         "$TOP"
    'language        "SPECTRE"
    'netlistFile     "$NL"
    'outputLib       "$LIB"
    'refLibList      "smic18mmrf analogLib"
    'outputViewType  "schematic"
    'outputViewName  "schematic"
    'simName         "spectre"
    'outputSimName   "spectre"
    'overwriteCells  "NONE"
    'logFile         "$ASLOG"
)
EOF
echo "IMPORT_COPY=$NL  TOP=$TOP  CELLS=$(echo "$CELLS" | wc -w)  MOS_LINES=$MOS"
echo "PARAM_FILE=$PARAM"

# shellcheck disable=SC1091
. "$PROJ/skill/cad_env.sh" || { echo "FATAL: cadence env load failed"; exit 8; }
cd "$S3C" || exit 9
[ -n "$(command -v spiceIn)" ] || { echo "FATAL: spiceIn not on the Cadence PATH"; exit 8; }

timeout "${TMO:-420}" spiceIn -param "$PARAM"
rc=$?
echo "ASG rc=$rc"
[ -f "$S3C/spiceIn.log" ] && cp -f "$S3C/spiceIn.log" "$LOGD/asg_cwdlog_$STAMP.log"
echo "ASG_LOG=$ASLOG"
echo "--- log tail ---"
tail -25 "$ASLOG" 2>&1
echo "--- error scan ---"
grep -icE 'error|\*\*E|not found|cannot|unable|refuse' "$ASLOG" 2>/dev/null | sed 's/^/ASG_PROBLEM_LINES: /'
echo "--- delivered views ---"
for C in $TOP $CELLS; do
  SCH=no; SYM=no
  [ -d "$S3C/$LIB/$C/schematic" ] && SCH=yes
  ls -d "$S3C/$LIB/$C"/symbol* >/dev/null 2>&1 && SYM=yes
  echo "CELL=$C schematic=$SCH symbol=$SYM"
done
[ "$rc" = "0" ] || { echo "S3C_ASG: FAIL"; exit 1; }
echo "S3C_ASG: DONE"
exit 0
