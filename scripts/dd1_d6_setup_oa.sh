#!/bin/bash
# DATA-6 section 8: this task's OWN isolated Virtuoso work directory.
#
# Same discipline as the accepted scripts/sc1_s3c_setup.sh, which this file is derived from and does
# not edit: the shared cadence_work/cds.lib belongs to the desktop launcher and to every earlier
# round, so it is READ, every DEFINE is carried over with relative paths made absolute against the
# directory the original lives in, and exactly one new line is appended for microled_data_d6. The
# shared file's md5 is printed before and after, so "unchanged" is a measured statement.
#
# The name guard is this task's own: nothing here may point at microled_cells, microled_scan_s3c or
# any other library.
#
#   bash scripts/dd1_d6_setup_oa.sh [libname]
set -u

PROJ="${PROJ:-/root/microled_ai_project}"
WORK="$PROJ/cadence_work"
D6="$WORK/data_d6_oa"
SHARED="$WORK/cds.lib"
LIBNAME="${1:-microled_data_d6}"

case "$LIBNAME" in
  microled_data_d6|dd1_d6_*) ;;
  *) echo "REFUSE: library name must be this task's own (got $LIBNAME)"; exit 9 ;;
esac
[ -r "$SHARED" ] || { echo "REFUSE: shared $SHARED unreadable"; exit 9; }

BEFORE=$(md5sum "$SHARED" | cut -d' ' -f1)
mkdir -p "$D6/skill" "$D6/asg_in" "$D6/logs" "$D6/home" "$D6/readback" "$D6/out"

if [ -e "$D6/cds.lib" ]; then
  echo "EXISTS: $D6/cds.lib is kept as it is (no rewrite, no clobber)"
else
  {
    echo "# DATA-6 dd1 isolated library map -- generated by scripts/dd1_d6_setup_oa.sh."
    echo "# Every DEFINE below is copied from $SHARED (read-only); relative paths are made"
    echo "# absolute against $WORK so the same libraries resolve from this cwd. One new line"
    echo "# is appended for this task's own library. The shared file is not modified."
    echo ""
    grep -E '^[[:space:]]*DEFINE' "$SHARED" \
      | sed -E "s|^([[:space:]]*DEFINE[[:space:]]+[^[:space:]]+[[:space:]]+)\./|\1$WORK/|"
    echo ""
    echo "DEFINE $LIBNAME $D6/$LIBNAME"
  } > "$D6/cds.lib"
  echo "WROTE: $D6/cds.lib"
fi

AFTER=$(md5sum "$SHARED" | cut -d' ' -f1)
echo "SHARED_CDS_LIB_MD5_BEFORE=$BEFORE"
echo "SHARED_CDS_LIB_MD5_AFTER=$AFTER"
[ "$BEFORE" = "$AFTER" ] && echo "SHARED_CDS_LIB_UNCHANGED: yes" || echo "SHARED_CDS_LIB_UNCHANGED: NO"
echo "SHARED_MENTIONS_TASK_LIB=$(grep -c "$LIBNAME" "$SHARED")"
echo "--- this task's map ---"
grep -E '^[[:space:]]*DEFINE' "$D6/cds.lib"
echo "--- DATA-6 tree ---"
ls -1 "$D6"
echo "D6_SETUP_OA: done lib=$LIBNAME dir=$D6/$LIBNAME"
exit 0
