#!/bin/bash
# SCAN-1 S3-C section 3: build this task's ISOLATED Virtuoso work directory.
#
# Why a new directory instead of reusing cadence_work: the shared cadence_work/cds.lib is used by
# the desktop launcher and by the SCH-1/2/3 and DATA cells. S3-C may add a library, it may not
# edit that map. So the map is READ, every registration is carried over unchanged, relative paths
# are made absolute against the directory the original lives in (otherwise "./microled_cells"
# would resolve inside s3c_oa and point at a non-existent library), and exactly one new line is
# appended for this task's own library.
#
# The shared file's md5 is taken before and after, so "unchanged" is a measured statement.
#
# Usage: bash scripts/sc1_s3c_setup.sh [libname]
set -u

PROJ="${PROJ:-/root/microled_ai_project}"
WORK="$PROJ/cadence_work"
S3C="$WORK/s3c_oa"
SHARED="$WORK/cds.lib"
LIBNAME="${1:-microled_scan_s3c}"

case "$LIBNAME" in
  sc1_s3c_*|microled_scan_s3c) ;;
  *) echo "REFUSE: library name must be this task's own (got $LIBNAME)"; exit 9 ;;
esac
[ -r "$SHARED" ] || { echo "REFUSE: shared $SHARED unreadable"; exit 9; }
[ -d "$WORK/microled_cells" ] || echo "NOTE: $WORK/microled_cells not present"

BEFORE=$(md5sum "$SHARED" | cut -d' ' -f1)
mkdir -p "$S3C/skill" "$S3C/asg_in" "$S3C/logs" "$S3C/home" "$S3C/readback" "$S3C/out"

if [ -e "$S3C/cds.lib" ]; then
  echo "EXISTS: $S3C/cds.lib is kept as it is (no rewrite, no clobber)"
else
  {
    echo "# SCAN-1 S3-C isolated library map -- generated by scripts/sc1_s3c_setup.sh."
    echo "# Every DEFINE below is copied from $SHARED (read-only); relative paths are"
    echo "# made absolute against $WORK so the same libraries resolve from this cwd. One"
    echo "# new line is appended for this task's own library. The shared file is not"
    echo "# modified: its md5 is printed before and after by the generating script."
    echo ""
    grep -E '^[[:space:]]*DEFINE' "$SHARED" \
      | sed -E "s|^([[:space:]]*DEFINE[[:space:]]+[^[:space:]]+[[:space:]]+)\./|\1$WORK/|"
    echo ""
    echo "DEFINE $LIBNAME $S3C/$LIBNAME"
  } > "$S3C/cds.lib"
  echo "WROTE: $S3C/cds.lib"
fi

AFTER=$(md5sum "$SHARED" | cut -d' ' -f1)
echo "SHARED_CDS_LIB_MD5_BEFORE=$BEFORE"
echo "SHARED_CDS_LIB_MD5_AFTER=$AFTER"
[ "$BEFORE" = "$AFTER" ] && echo "SHARED_CDS_LIB_UNCHANGED: yes" || echo "SHARED_CDS_LIB_UNCHANGED: NO"
echo "SHARED_MENTIONS_TASK_LIB=$(grep -c "$LIBNAME" "$SHARED")"
echo "--- this task's map ---"
grep -E '^[[:space:]]*DEFINE' "$S3C/cds.lib"
echo "--- S3C tree ---"
ls -1 "$S3C"
echo "S3C_SETUP: done lib=$LIBNAME dir=$S3C/$LIBNAME"
exit 0
