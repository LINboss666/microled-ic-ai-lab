#!/usr/bin/env python2
# -*- coding: utf-8 -*-
"""SCAN-1 S3C2: turn the placement plan CSV into the SKILL table the applier reads.

The generated file loads skill/sc1_s3c2_apply_sym.il (procedure definitions only, so nothing runs at
load time), sets s3c2OnlyCell, and calls s2aApply with the rows. Body rows carry nil in the fields
they do not use -- the applier reads only the ones it needs.

usage: python scripts/sc1_s3c2_emit_il.py <plan.csv> <out.il> [--only-cell NAME] [--oa-dir DIR]
"""
from __future__ import print_function
import io
import os
import sys

HEAD = [';; generated by scripts/sc1_s3c2_emit_il.py from %s -- do not edit by hand',
        ';; %d rows, cell filter: %s',
        'load("%s/skill/sc1_s3c2_apply_sym.il")',
        's3c2OnlyCell = %s',
        's3c2Rows = list(']
TAIL = [')', 'printf("S3C2A-ROWS %L\\n" length(s3c2Rows))', 's2aApply(s3c2Rows)', 'nil']


def main():
    plan, out = sys.argv[1], sys.argv[2]
    only = sys.argv[sys.argv.index('--only-cell') + 1] if '--only-cell' in sys.argv else None
    oa = sys.argv[sys.argv.index('--oa-dir') + 1] if '--oa-dir' in sys.argv \
        else '/root/microled_ai_project/cadence_work/s3c_oa'
    lines = [l.rstrip('\n') for l in io.open(plan, encoding='utf-8') if l.strip()]
    hdr = lines[0].split(',')
    rows = [r for r in (l.split(',') for l in lines[1:]) if only is None or r[1] == only]
    # SKILL's nested load (this file is itself loaded from the isolated .cdsinit) leaves the
    # procedures defined by the inner load unbound at the call site -- measured: the cell-selection
    # loop inside s2aApply ran, then the next s2aAt call raised "unbound variable - s2aAt". So the
    # applier text goes in here, one self-contained file, the way the direction writer was.
    applier = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, 'skill',
                           'sc1_s3c2_apply_sym.il')
    body = io.open(applier, encoding='utf-8').read()
    body = body.replace('s3c2aLib = "microled_scan_s3c"', 's3c2aLib = "microled_scan_s3c"', 1)
    with io.open(out, 'wb') as fh:
        for h in [HEAD[0] % (plan.split('/')[-1],),
                  HEAD[1] % (len(rows), only or 'ALL'),
                  u';; the applier procedures are inlined from skill/sc1_s3c2_apply_sym.il',
                  body,
                  HEAD[3] % (only is None and 'nil' or '"%s"' % only,),
                  HEAD[4]]:
            fh.write((h + u'\n').encode('utf-8'))
        # Row layout kept whole: the old rectangle box is the lookup key for the STUB and the NAME
        # (measured: after a rect has moved, keying the group on the current rect centre picks up
        # another pin's stub), while the pin rectangle itself is located through its own terminal,
        # so a repeated application can only ever be a no-op.
        keep = list(range(0, len(hdr)))
        for r0 in rows:
            if len(r0) != len(hdr):
                raise ValueError('row width %d != header %d' % (len(r0), len(hdr)))
            r = [r0[i] for i in keep]
            items = []
            for i, v in enumerate(r):
                if i < 3:
                    items.append(u'"%s"' % v)
                elif v == '':
                    items.append(u'nil')
                else:
                    try:
                        float(v)
                        items.append(u'%s' % v)
                    except ValueError:
                        # a non-numeric field (the justification word) must be a STRING, or SKILL
                        # evaluates it as a variable: "unbound variable - centerLeft"
                        items.append(u'"%s"' % v)
            fh.write((u'  list(%s)\n' % u' '.join(items)).encode('utf-8'))
        for t in TAIL:
            fh.write((t + u'\n').encode('utf-8'))
    cells = sorted(set(r[1] for r in rows))
    print('S3C2_EMIT wrote %s rows=%d cells=%s kinds=%s'
          % (out, len(rows), cells, sorted(set(r[0] for r in rows))))


main()
